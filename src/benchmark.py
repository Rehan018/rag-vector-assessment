from pathlib import Path
from typing import List

from tabulate import tabulate

from src.config import config
from src.data_loader import DataLoader
from src.embeddings import SentenceTransformerEmbeddingProvider
from src.models import BenchmarkCase, RetrievalResult
from src.query_expander import MockQueryExpander
from src.retriever import Retriever
from src.vector_store import FaissVectorStore


BENCHMARK_QUERIES = [
    "How does the system handle peak load?",
    "What happens when background jobs fail repeatedly?",
    "How can we know if retrieval quality is getting worse?",
]


class BenchmarkRunner:
    """
    Runs Strategy A vs Strategy B retrieval comparisons.

    Strategy A uses the raw user query.
    Strategy B expands the query before embedding and retrieval.
    """

    def __init__(self, retriever: Retriever, top_k: int):
        self.retriever = retriever
        self.top_k = top_k

    def run(self, queries: List[str]) -> List[BenchmarkCase]:
        cases: List[BenchmarkCase] = []

        for query in queries:
            raw_results = self.retriever.retrieve_raw(
                query=query,
                top_k=self.top_k,
            )

            expanded_query, expanded_results = self.retriever.retrieve_with_expansion(
                query=query,
                top_k=self.top_k,
            )

            cases.append(
                BenchmarkCase(
                    query=query,
                    expanded_query=expanded_query,
                    strategy_a_results=raw_results,
                    strategy_b_results=expanded_results,
                )
            )

        return cases

    def write_markdown_report(
        self,
        cases: List[BenchmarkCase],
        output_path: str,
    ) -> None:
        path = Path(output_path)

        lines = [
            "# Retrieval Benchmark: Strategy A vs Strategy B",
            "",
            "This file is generated by running the local benchmark pipeline.",
            "",
            "The goal of this benchmark is to compare how retrieval changes when the same user query is searched directly versus when it is first rewritten into a more embedding-friendly query.",
            "",
            "This is not meant to prove that query expansion is always better. The goal is to make the retrieval behavior visible and easy to inspect.",
            "",
            "## Benchmark Setup",
            "",
            "- Corpus: local technical corpus with 10 chunks",
            "- Embedding model: sentence-transformers/all-MiniLM-L6-v2",
            "- Vector store: FAISS",
            "- Similarity: inner product over normalized embeddings, equivalent to cosine-style similarity",
            f"- Top-k: {self.top_k}",
            "- Strategy A: embed the raw user query and search directly",
            "- Strategy B: expand the query first, then embed and search",
            "",
            "## Queries Used",
            "",
            "The benchmark uses three queries that represent common retrieval problems:",
            "",
            "1. A scalability query about peak load handling",
            "2. A reliability query about repeated background job failures",
            "3. An evaluation query about detecting retrieval quality degradation",
            "",
        ]

        for index, case in enumerate(cases, start=1):
            lines.extend(
                [
                    f"## Query {index}",
                    "",
                    f"Original query: `{case.query}`",
                    "",
                    f"Expanded query: `{case.expanded_query}`",
                    "",
                    "### Strategy A: Raw Vector Search",
                    "",
                    self._format_results_table(case.strategy_a_results),
                    "",
                    "### Strategy B: AI-Enhanced Retrieval",
                    "",
                    self._format_results_table(case.strategy_b_results),
                    "",
                    "### Observation",
                    "",
                    self._build_observation(case),
                    "",
                ]
            )

        lines.extend(
            [
                "## Overall Takeaway",
                "",
                "Query expansion is useful when the original user query is short, vague, or does not contain the same terms used in the indexed corpus.",
                "",
                "The main benefit is improved recall: the expanded query can include related operational terms such as queue depth, backpressure, retry budget, dead-letter queue, ranking, or retrieval quality metrics.",
                "",
                "The main risk is query drift. If the expansion model adds concepts that the user did not intend, retrieval can move toward a different topic. For that reason, I would evaluate query expansion continuously instead of assuming it is always better.",
                "",
                "In a production system, I would keep both raw and expanded retrieval available. If the expanded query produces weak scores or unstable results, the system could fall back to raw retrieval or combine both result sets before reranking.",
                "",
            ]
        )

        path.write_text("\n".join(lines), encoding="utf-8")

    def _format_results_table(self, results: List[RetrievalResult]) -> str:
        table = [
            [
                result.rank,
                result.chunk_id,
                result.title,
                f"{result.score:.4f}",
            ]
            for result in results
        ]

        return tabulate(
            table,
            headers=["Rank", "Chunk ID", "Title", "Score"],
            tablefmt="github",
        )

    def _build_observation(self, case: BenchmarkCase) -> str:
        raw_top = case.strategy_a_results[0]
        expanded_top = case.strategy_b_results[0]

        raw_titles = [result.title for result in case.strategy_a_results]
        expanded_titles = [result.title for result in case.strategy_b_results]

        if raw_top.chunk_id == expanded_top.chunk_id:
            return (
                f"Both strategies ranked `{raw_top.title}` first. "
                "That is a good sign because the expanded query did not drift away from the user's intent. "
                f"The lower-ranked results changed from {raw_titles} to {expanded_titles}, "
                "which shows that query expansion can still affect recall even when the top result stays the same."
            )

        return (
            f"Strategy A ranked `{raw_top.title}` first, while Strategy B ranked `{expanded_top.title}` first. "
            "This shows that query expansion changed the retrieval behavior. "
            "That can be helpful when the rewritten query adds missing technical context, "
            "but it also needs evaluation because an aggressive rewrite can move retrieval away from the original intent."
        )


def build_default_retriever() -> Retriever:
    loader = DataLoader(config.corpus_path)
    chunks = loader.load()

    embedding_provider = SentenceTransformerEmbeddingProvider(
        model_name=config.embedding_model_name
    )

    document_embeddings = embedding_provider.embed_texts(
        [chunk.text for chunk in chunks]
    )

    vector_store = FaissVectorStore(dimension=config.vector_dimension)
    vector_store.add_documents(chunks, document_embeddings)

    return Retriever(
        embedding_provider=embedding_provider,
        vector_store=vector_store,
        query_expander=MockQueryExpander(),
    )


def main() -> None:
    retriever = build_default_retriever()

    runner = BenchmarkRunner(
        retriever=retriever,
        top_k=config.top_k,
    )

    cases = runner.run(BENCHMARK_QUERIES)

    runner.write_markdown_report(
        cases=cases,
        output_path=config.benchmark_output_path,
    )

    print(f"Benchmark written to {config.benchmark_output_path}")


if __name__ == "__main__":
    main()